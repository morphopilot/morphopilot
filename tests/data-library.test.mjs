import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/data-library.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {annotationHref,allTilesReviewed,containedImagePoint,selectLibraryVolumes,volumeMaskState}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const original={id:'vol_a',name:'Brain 10.tif',status:'ready',total_tiles:30,confirmed_tiles:0,revision:0,merge_status:'none',tile_shape:[25,192,192],created_at:10};
const done={...original,id:'vol_b',name:'Brain 2.tif',confirmed_tiles:30,revision:60,merge_status:'ready',merge_revision:60,created_at:20};
const failed={...original,id:'vol_c',name:'Import failure.tif',status:'failed',error:'Invalid ZYX axes',created_at:30};
assert.equal(annotationHref('spot','vol with space','tile&1',2),'/?category=spot&volume=vol+with+space&tile=tile%261&z=3');
assert.equal(annotationHref('neurite','vol_a'),'/?category=neurite&volume=vol_a');
assert.equal(annotationHref('neurite',undefined,undefined,10),'/?category=neurite');
assert.equal(volumeMaskState(original).label,'Not annotated yet');
assert.equal(volumeMaskState({...original,revision:1}).label,'Annotation in progress');
assert.equal(volumeMaskState(done).label,'Merged mask ready');
assert.equal(volumeMaskState({...done,merge_revision:59}).label,'All tiles reviewed');
assert.equal(volumeMaskState({...done,confirmed_tiles:29}).label,'Annotation in progress');
assert.equal(allTilesReviewed({...done,total_tiles:0,confirmed_tiles:0}),false);
assert.equal(volumeMaskState(failed).description,'Invalid ZYX axes');
const volumes=[original,done,failed];
assert.deepEqual(selectLibraryVolumes(volumes,'','all','newest').map(v=>v.id),['vol_c','vol_b','vol_a']);
assert.deepEqual(selectLibraryVolumes(volumes,'brain','all','name').map(v=>v.id),['vol_b','vol_a']);
assert.deepEqual(selectLibraryVolumes(volumes,'','reviewing','newest').map(v=>v.id),['vol_a']);
assert.deepEqual(selectLibraryVolumes(volumes,'','reviewed','newest').map(v=>v.id),['vol_b']);
assert.deepEqual(selectLibraryVolumes(volumes,'','preparing','newest').map(v=>v.id),['vol_c']);
assert.deepEqual(selectLibraryVolumes(volumes,' VOL_A ','all','newest').map(v=>v.id),['vol_a']);
assert.equal(selectLibraryVolumes(volumes,'missing','all','newest').length,0);
assert.deepEqual(volumes.map(v=>v.id),['vol_a','vol_b','vol_c']);
// A 200 x 100 image centered inside a square canvas has vertical letterboxing.
assert.equal(containedImagePoint(50,25,{left:0,top:0,width:200,height:200},[100,200]),null);
assert.deepEqual(containedImagePoint(100,100,{left:0,top:0,width:200,height:200},[100,200]),{x:100,y:50});
assert.deepEqual(containedImagePoint(200,160,{left:100,top:10,width:200,height:300},[100,200]),{x:100,y:50});
assert.equal(containedImagePoint(200,100,{left:0,top:0,width:200,height:200},[100,200]),null);
console.log('PASS: library filtering, progress classification, stale merge status, encoded annotation links, and exact clicks through canvas letterboxing');
